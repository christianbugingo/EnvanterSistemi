CREATE TABLE IF NOT EXISTS stock_batches (
 batch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 product_id INT NOT NULL REFERENCES products(product_id) ON DELETE CASCADE,
 unit VARCHAR(10) NOT NULL,
 quantity_received BIGINT NOT NULL CHECK(quantity_received>0),
 remaining_quantity BIGINT NOT NULL CHECK(remaining_quantity>=0 AND remaining_quantity<=quantity_received),
 total_cost DECIMAL(19,4), remaining_cost DECIMAL(19,4), cost_per_unit DECIMAL(30,12),
 received_date DATE NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 currency_code VARCHAR(3), currency_minor INT NOT NULL DEFAULT 2,
 selling_price DECIMAL(19,4), opening_key VARCHAR(60) UNIQUE,
 CHECK(total_cost IS NULL OR total_cost>=0), CHECK(remaining_cost IS NULL OR remaining_cost>=0)
);
CREATE INDEX IF NOT EXISTS ix_batch_fifo ON stock_batches(product_id,received_date,batch_id);
CREATE TABLE IF NOT EXISTS sale_batch_allocations (
 sale_id INT NOT NULL REFERENCES sales(sale_id), batch_id BIGINT NOT NULL REFERENCES stock_batches(batch_id),
 quantity_used BIGINT NOT NULL CHECK(quantity_used>0), cost_amount DECIMAL(19,4),
 unit_cost_snapshot DECIMAL(30,12), currency_code VARCHAR(3), currency_minor INT NOT NULL,
 PRIMARY KEY(sale_id,batch_id)
);
ALTER TABLE sales ADD COLUMN IF NOT EXISTS cost_of_goods DECIMAL(19,4);
ALTER TABLE sales ADD COLUMN IF NOT EXISTS cost_complete BOOLEAN NOT NULL DEFAULT FALSE;
